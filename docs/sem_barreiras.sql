CREATE TABLE "equipamentos_solicitacaoequipamento" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "protocolo" varchar(24) NOT NULL UNIQUE,
    "tipo_equipamento" varchar(30) NOT NULL,
    "largura_quadril_cm" smallint NOT NULL,
    "altura_cm" smallint NOT NULL,
