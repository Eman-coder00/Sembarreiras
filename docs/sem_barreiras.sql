-- ============================================================================
-- ITEM 2 (1,0 PONTO): CRIAÇÃO DE CAMPOS INDEXADOS (CREATE INDEX)
-- ============================================================================
-- Índices B-Tree compostos e parciais criados para acelerar buscas críticas:
--   1. Índice único parcial garantindo que um titular PCD não tenha dois
--      contatos ativos na mesma ordem de prioridade (status = 1).
--   2. Índice composto na frota de ônibus filtrando apenas veículos com
--      acessibilidade física ativa (elevador/rampa funcional - RF010).
--   3. Índices de busca rápida de consultas, ocorrências de pânico e
--      empréstimos de equipamentos por beneficiário, status e data.
-- ============================================================================

BEGIN;

-- Índice único parcial: apenas 1 contato ativo por nível de prioridade (1º, 2º, 3º) para cada PCD
CREATE UNIQUE INDEX IF NOT EXISTS "emergencia_prioridade_ativa_unica_por_titular"
    ON "emergencia_contatoemergencia" ("titular_pcd_id", "prioridade")
    WHERE "status" = 1;

-- Índice composto para filtragem rápida de ônibus com acessibilidade ativa por linha
CREATE INDEX IF NOT EXISTS "idx_veiculoadaptado_acessibilidade_linha"
    ON "transporte_veiculoadaptado" ("acessibilidade_ativa", "linha_id");

-- Índice composto para busca de consultas de um paciente PCD ordenadas por status e vaga
CREATE INDEX IF NOT EXISTS "idx_consulta_paciente_status_vaga"
    ON "agendamentos_consulta" ("paciente_pcd_id", "status", "vaga_id");

-- Índice composto para consulta de vagas disponíveis na ADEFAL por especialidade e data
CREATE INDEX IF NOT EXISTS "idx_vaga_adefal_disponivel_especialidade_data"
    ON "agendamentos_vagaagendaadefal" ("disponivel", "especialidade", "data");

-- Índice composto para monitoramento de vencimento de empréstimos de equipamentos
CREATE INDEX IF NOT EXISTS "idx_equipamento_status_vencimento"
    ON "equipamentos_solicitacaoequipamento" ("status", "data_vencimento_emprestimo");

-- Índice composto para histórico de ocorrências de pânico por titular e data de criação
CREATE INDEX IF NOT EXISTS "idx_ocorrenciapanico_titular_data"
    ON "emergencia_ocorrenciapanico" ("titular_pcd_id", "criado_em" DESC);

COMMIT;


-- ============================================================================
-- ITEM 3 (1,0 PONTO): CRIAÇÃO DE TRIGGER NO BANCO DE DADOS
-- ============================================================================
-- Trigger: trg_proteger_cpf_e_auditar_usuario
-- Objetivo de Negócio (RS007 / RF002):
--   1. Impede no nível do SGBD qualquer tentativa de alterar o CPF de um
--      usuário após o cadastro (garantindo imutabilidade absoluta do CPF).
--   2. Registra automaticamente um log de auditoria na tabela
--      "contas_logauditoriaconta" sempre que o status cadastral da conta for
--      alterado (ex.: inativação LGPD) ou quando a conta sofrer bloqueio
--      temporário por tentativas falhas de login.
-- ============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION fn_proteger_cpf_e_auditar_usuario()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- 1. Regra de Imutabilidade do CPF (exceto mascaramento de inativação LGPD status = 3)
    IF NEW.cpf <> OLD.cpf AND NEW.status_cadastro <> 3 THEN
        RAISE EXCEPTION 'Violação de integridade (RS007): O CPF do usuário (%) é imutável após o cadastro.', OLD.cpf;
    END IF;

    -- 2. Auditoria automática de bloqueio temporário por força bruta (RS002)
    IF NEW.bloqueado_ate IS DISTINCT FROM OLD.bloqueado_ate AND NEW.bloqueado_ate IS NOT NULL THEN
        INSERT INTO "contas_logauditoriaconta" ("evento", "detalhes", "ip", "criado_em", "usuario_id")
        VALUES (
            'TRIGGER_BLOQUEIO_CONTA',
            'Bloqueio temporário detectado pelo SGBD até ' || TO_CHAR(NEW.bloqueado_ate, 'DD/MM/YYYY HH24:MI:SS'),
            'SGBD_TRIGGER',
            CURRENT_TIMESTAMP,
            NEW.id
        );
    END IF;

    -- 3. Auditoria automática de mudança de status cadastral (Ativo -> Inativo/LGPD)
    IF NEW.status_cadastro <> OLD.status_cadastro THEN
        INSERT INTO "contas_logauditoriaconta" ("evento", "detalhes", "ip", "criado_em", "usuario_id")
        VALUES (
            'TRIGGER_MUDANCA_STATUS_CONTA',
            'Status cadastral alterado de ' || OLD.status_cadastro || ' para ' || NEW.status_cadastro,
            'SGBD_TRIGGER',
            CURRENT_TIMESTAMP,
            NEW.id
        );
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_cpf_e_auditar_usuario ON "contas_usuario";

CREATE TRIGGER trg_proteger_cpf_e_auditar_usuario
BEFORE UPDATE ON "contas_usuario"
FOR EACH ROW
EXECUTE FUNCTION fn_proteger_cpf_e_auditar_usuario();

COMMIT;


-- ============================================================================
-- ITEM 4 (1,0 PONTO): CRIAÇÃO DE VIEW NO BANCO DE DADOS
-- ============================================================================
-- View: vw_painel_consultas_e_transporte_adefal
-- Objetivo:
--   Consolida em uma única visão gerencial para a recepção/portaria e equipe
--   clínica da ADEFAL os dados da consulta agendada, identificação do paciente
--   PCD, tipo de deficiência física, especialidade, unidade, data/horário,
--   assinatura do QR Code e, caso solicitado, os dados da van adaptada do
--   transporte hospitalar porta a porta.
-- ============================================================================

BEGIN;

CREATE OR REPLACE VIEW vw_painel_consultas_e_transporte_adefal AS
SELECT
    c.id AS consulta_id,
    c.protocolo AS protocolo_consulta,
    c.status AS status_consulta,
    c.assinatura_qr,
    u.cpf AS paciente_cpf,
    u.nome_completo AS paciente_nome,
    u.telefone AS paciente_telefone,
    p.tipo_deficiencia,
    p.equipamentos_apoio,
    v.especialidade,
    v.unidade AS unidade_adefal,
    v.profissional AS profissional_responsavel,
    v.data AS data_consulta,
    v.horario AS horario_consulta,
    st.id AS solicitacao_transporte_id,
    st.endereco_embarque,
    st.horario_apanhe_previsto,
    st.precisa_acompanhante,
    st.status AS status_transporte,
    f.veiculo_identificacao AS van_adaptada,
    f.motorista AS motorista_van
FROM "agendamentos_consulta" c
INNER JOIN "contas_usuario" u
    ON u.id = c.paciente_pcd_id
LEFT JOIN "contas_perfilpcd" p
    ON p.usuario_id = u.id
INNER JOIN "agendamentos_vagaagendaadefal" v
    ON v.id = c.vaga_id
LEFT JOIN "agendamentos_solicitacaotransporte" st
    ON st.consulta_id = c.id
LEFT JOIN "agendamentos_vagafrotaadaptada" f
    ON f.id = st.frota_id;

COMMIT;


