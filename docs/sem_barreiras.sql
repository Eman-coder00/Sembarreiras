-- 1.12. Tabela de Veículos Adaptados (Telemetria e Elevador/Rampa Funcional)
CREATE TABLE "transporte_veiculoadaptado" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "prefixo" varchar(20) NOT NULL UNIQUE,
    "acessibilidade_ativa" boolean NOT NULL DEFAULT true,
    "tipo_equipamento" varchar(30) NOT NULL,
