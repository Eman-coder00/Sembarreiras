--
-- 1. INTRODUÇÃO DO PROJETO:
-- O SemBarreiras (MobiLivre — ADEFAL) é uma plataforma voltada à autonomia,
-- mobilidade urbana acessível e assistência em saúde de Pessoas com Deficiência
-- Física (PCD) atendidas pela ADEFAL (Associação dos Deficientes Físicos de
-- Alagoas) e seus cuidadores/tutores legais.
-- O banco de dados relacional gerencia 5 domínios integrados:
--   (a) Contas, Perfis de Acessibilidade Motora e Vínculos de Cuidadores via OTP;
--   (b) Emergência com Contatos Prioritários (1ª a 3ª ordem) e Botão de Pânico;
--   (c) Transporte Urbano Acessível com Rastreamento GPS e Cálculo de ETA;
--   (d) Agendamento de Consultas na ADEFAL, Vans Adaptadas e Comprovante QR Code;
--   (e) Empréstimo de Equipamentos Ortopédicos, Laudos Médicos e Linha do Tempo.
--
-- 2. DECLARAÇÃO DE USO DE IA (CONFORME SOLICITADO NA AVALIAÇÃO):
--   - Modelo de IA utilizado: Google Gemini (via Antigravity IDE)
--   - Prompt utilizado:
--     "Atue como um Engenheiro e Administrador de Banco de Dados (DBA) especialista
--      em PostgreSQL. Com base nos requisitos do sistema SemBarreiras (ADEFAL),
--      elabore o script SQL puro dividido nos 5 critérios da avaliação 3AF:
--      (1) DDL de criação das tabelas de domínio garantindo explicitamente as
--      4 integridades relacionais (Entidade com PRIMARY KEY IDENTITY, Referencial
--      com FOREIGN KEY e ações ON DELETE, Domínio com tipos estritos, NOT NULL,
--      DEFAULT e cláusulas CHECK para limites antropométricos, prioridades 1..3 e
--      ocupação de frota, e Definida pelo Usuário/Negócio com UNIQUE e constraints
--      compostas);
--      (2) Criação de índices estratégicos (CREATE INDEX e UNIQUE INDEX parcial)
--      para otimizar consultas por CPF, protocolo, frota acessível ativa e agenda;
--      (3) Criação de uma Trigger em PL/pgSQL que garanta a imutabilidade do CPF
--      após o cadastro e registre auditoria automática em contas_logauditoriaconta
--      quando houver alteração de status ou bloqueio da conta;
--      (4) Criação de uma View gerencial unindo consultas, pacientes PCD, perfil
--      de deficiência, grade da ADEFAL e transporte hospitalar adaptado;
--      (5) Comandos DCL (CREATE ROLE, GRANT e REVOKE) aplicando o princípio do
--      menor privilégio e conformidade com a LGPD para a aplicação, equipe de
--      triagem e portaria."
-- ============================================================================


-- ============================================================================
-- ITEM 1 (1,0 PONTO): CRIAÇÃO DAS TABELAS (DDL) MANTENDO AS 4 INTEGRIDADES
-- ============================================================================
-- Resumo das 4 Integridades aplicadas abaixo:
--   [1] Integridade de Entidade: Todas as tabelas possuem chave primária
--       ("id" BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY).
--   [2] Integridade Referencial: Chaves estrangeiras (FOREIGN KEY ... REFERENCES)
--       com políticas explícitas (ON DELETE RESTRICT / CASCADE).
--   [3] Integridade de Domínio: Tipagem forte, NOT NULL, DEFAULT e restrições
--       CHECK validando intervalos clínicos, prioridades (1 a 3) e saldos (>= 0).
--   [4] Integridade Definida pelo Usuário (Negócio): Restrições UNIQUE simples
--       (CPF, e-mail, protocolos) e compostas (vínculo único cuidador-titular,
--       alocação única de profissional/unidade/data/horário).
-- ============================================================================

BEGIN;

-- 1.1. Tabela de Usuários (Titulares PCD, Cuidadores e Equipe ADEFAL)
CREATE TABLE "contas_usuario" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "password" varchar(128) NOT NULL,
    "last_login" timestamp with time zone NULL,
    "is_superuser" boolean NOT NULL DEFAULT false,
    "username" varchar(150) NOT NULL UNIQUE,
    "first_name" varchar(150) NOT NULL DEFAULT '',
    "last_name" varchar(150) NOT NULL DEFAULT '',
    "is_staff" boolean NOT NULL DEFAULT false,
    "is_active" boolean NOT NULL DEFAULT true,
    "date_joined" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "cpf" varchar(14) NOT NULL UNIQUE,
    "nome_completo" varchar(120) NOT NULL,
    "email" varchar(200) NOT NULL UNIQUE,
    "telefone" varchar(15) NOT NULL,
    "data_nascimento" date NULL,
    "papel" varchar(12) NOT NULL DEFAULT 'PCD',
    "status_cadastro" integer NOT NULL DEFAULT 1,
    "tentativas_login_falhas" smallint NOT NULL DEFAULT 0,
    "bloqueado_ate" timestamp with time zone NULL,
    "versao_sessao" integer NOT NULL DEFAULT 1,
    "criado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "chk_usuario_papel_dominio"
        CHECK ("papel" IN ('PCD', 'CUIDADOR', 'ADMIN')),
    CONSTRAINT "chk_usuario_status_cadastro_dominio"
        CHECK ("status_cadastro" IN (1, 2, 3)),
    CONSTRAINT "chk_usuario_tentativas_nao_negativas"
        CHECK ("tentativas_login_falhas" >= 0),
    CONSTRAINT "chk_usuario_versao_sessao_positiva"
        CHECK ("versao_sessao" >= 0)
);

-- 1.2. Tabela de Perfil de Acessibilidade Motora e Endereço do Usuário PCD
CREATE TABLE "contas_perfilpcd" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "tipo_deficiencia" varchar(40) NOT NULL,
    "equipamentos_apoio" varchar(200) NOT NULL,
    "tamanho_toque" varchar(20) NOT NULL DEFAULT 'PADRAO',
    "timeout_tela" varchar(20) NOT NULL DEFAULT 'PADRAO',
    "alto_contraste" boolean NOT NULL DEFAULT false,
    "cep" varchar(9) NOT NULL,
    "logradouro" varchar(100) NOT NULL,
    "numero" varchar(10) NOT NULL,
    "complemento" varchar(100) NOT NULL DEFAULT '',
    "bairro" varchar(100) NOT NULL,
    "municipio" varchar(100) NOT NULL,
    "uf" varchar(2) NOT NULL DEFAULT 'AL',
    "usuario_id" bigint NOT NULL UNIQUE,
    CONSTRAINT "chk_perfilpcd_tamanho_toque_dominio"
        CHECK ("tamanho_toque" IN ('PADRAO', 'EXPANDIDO', 'MAXIMO')),
    CONSTRAINT "fk_perfilpcd_usuario"
        FOREIGN KEY ("usuario_id") REFERENCES "contas_usuario" ("id")
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- 1.3. Tabela de Vínculo entre Cuidador/Tutor Legal e Titular PCD (com OTP)
CREATE TABLE "contas_vinculocuidador" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "grau_parentesco" varchar(30) NOT NULL,
    "codigo_otp" varchar(6) NOT NULL,
    "status" integer NOT NULL DEFAULT 1,
    "criado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "atualizado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "cuidador_id" bigint NOT NULL,
    "titular_pcd_id" bigint NOT NULL,
    CONSTRAINT "unico_vinculo_cuidador_titular"
        UNIQUE ("cuidador_id", "titular_pcd_id"),
    CONSTRAINT "chk_vinculo_usuarios_distintos"
        CHECK ("cuidador_id" <> "titular_pcd_id"),
    CONSTRAINT "chk_vinculo_status_dominio"
        CHECK ("status" IN (1, 2, 3)),
    CONSTRAINT "fk_vinculo_cuidador"
        FOREIGN KEY ("cuidador_id") REFERENCES "contas_usuario" ("id")
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "fk_vinculo_titular_pcd"
        FOREIGN KEY ("titular_pcd_id") REFERENCES "contas_usuario" ("id")
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- 1.4. Tabela de Tokens Temporários de Recuperação de Senha
CREATE TABLE "contas_tokenrecuperacaosenha" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "codigo" varchar(6) NOT NULL,
    "expira_em" timestamp with time zone NOT NULL,
    "utilizado" boolean NOT NULL DEFAULT false,
    "criado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "usuario_id" bigint NOT NULL,
    CONSTRAINT "fk_tokenrecuperacao_usuario"
        FOREIGN KEY ("usuario_id") REFERENCES "contas_usuario" ("id")
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- 1.5. Tabela Imutável de Log de Auditoria de Contas e Segurança
CREATE TABLE "contas_logauditoriaconta" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "evento" varchar(60) NOT NULL,
    "detalhes" text NOT NULL,
    "ip" varchar(45) NOT NULL DEFAULT '',
    "criado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "usuario_id" bigint NOT NULL,
    CONSTRAINT "fk_logauditoria_usuario"
        FOREIGN KEY ("usuario_id") REFERENCES "contas_usuario" ("id")
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED
);

-- 1.6. Tabela de Base Local de CEPs (Maceió / Alagoas)
CREATE TABLE "contas_ceplocal" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "cep" varchar(9) NOT NULL UNIQUE,
    "logradouro" varchar(100) NOT NULL,
    "bairro" varchar(100) NOT NULL,
    "municipio" varchar(100) NOT NULL,
    "uf" varchar(2) NOT NULL DEFAULT 'AL'
);

-- 1.7. Tabela de Contatos Prioritários de Emergência (1ª, 2ª e 3ª Prioridade)
CREATE TABLE "emergencia_contatoemergencia" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "nome" varchar(100) NOT NULL,
    "telefone" varchar(15) NOT NULL,
    "parentesco" varchar(20) NOT NULL,
    "prioridade" smallint NOT NULL,
    "status" integer NOT NULL DEFAULT 1,
    "criado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "titular_pcd_id" bigint NOT NULL,
    CONSTRAINT "emergencia_contato_prioridade_1_a_3"
        CHECK ("prioridade" >= 1 AND "prioridade" <= 3),
    CONSTRAINT "chk_contato_status_dominio"
        CHECK ("status" IN (1, 2)),
    CONSTRAINT "fk_contatoemergencia_titular_pcd"
        FOREIGN KEY ("titular_pcd_id") REFERENCES "contas_usuario" ("id")
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- 1.8. Tabela de Ocorrências do Botão de Pânico (Geolocalização e Fallback SMS)
CREATE TABLE "emergencia_ocorrenciapanico" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "codigo" varchar(24) NOT NULL UNIQUE,
    "latitude" double precision NULL,
    "longitude" double precision NULL,
    "endereco_aproximado" varchar(200) NOT NULL DEFAULT '',
    "status" varchar(20) NOT NULL,
    "contatos_notificados" text NOT NULL DEFAULT '',
    "mensagem_enviada" text NOT NULL DEFAULT '',
    "criado_em" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "finalizado_em" timestamp with time zone NULL,
    "titular_pcd_id" bigint NOT NULL,
    CONSTRAINT "chk_ocorrencia_coordenadas_geograficas"
        CHECK (
            ("latitude" IS NULL OR ("latitude" BETWEEN -90.0 AND 90.0))
            AND ("longitude" IS NULL OR ("longitude" BETWEEN -180.0 AND 180.0))
        ),
    CONSTRAINT "fk_ocorrenciapanico_titular_pcd"
        FOREIGN KEY ("titular_pcd_id") REFERENCES "contas_usuario" ("id")
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED
);

-- 1.9. Tabela de Linhas de Ônibus Urbanos
CREATE TABLE "transporte_linhaonibus" (
