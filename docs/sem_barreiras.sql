);

-- 1.13. Tabela de Grade de Vagas de Consultas e Reabilitação na ADEFAL
CREATE TABLE "agendamentos_vagaagendaadefal" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "especialidade" varchar(30) NOT NULL,
